"""Build the Emotes fallback index from the installed SR2 animation tables.

Run with the port's vpp.py module on PYTHONPATH and the game directory as the
first argument. The output contains names only, with no game assets.
"""

import json
from collections import defaultdict
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

from vpp import Pack


def build(game, output):
    tables = {}
    clips = set()
    for filename in ("anims.vpp_pc", "common.vpp_pc", "patch.vpp_pc", "m_pat.vpp_pc"):
        pack = Pack(game / filename)
        for entry in pack.entries:
            name = entry["name"].lower()
            if name.endswith(".xtbl") and filename != "anims.vpp_pc":
                tables[name] = (pack, entry)
            elif name.endswith(".anim_pc"):
                clips.add(name.removesuffix(".anim_pc"))

    loose_tables = {}
    for folder in ("DLC", "Mods"):
        for path in sorted((game / folder).rglob("*")):
            name = path.name.lower()
            if name.endswith(".anim_pc"):
                clips.add(name.removesuffix(".anim_pc"))
            elif name.endswith(".xtbl"):
                loose_tables[name] = path

    def table(name):
        if name in loose_tables:
            return ET.fromstring(loose_tables[name].read_bytes())
        pack, entry = tables[name]
        return ET.fromstring(pack.read(entry))

    manifest = table("anim_set_filenames.xtbl")
    sets = {
        entry.findtext("Name").lower()
        for entry in manifest.findall("./Table/Anim_Set_Filename")
        if entry.findtext("Default_rig", "").lower() == "sr2_main_rig.rig_pc"
    }
    preferred = ("gml1.xtbl", "gfl1.xtbl", "pml1.xtbl", "pfl1.xtbl", "cml1.xtbl")
    maps = {"State": defaultdict(list), "Action": defaultdict(list)}
    for name in sorted(sets, key=lambda n: (preferred.index(n) if n in preferred else len(preferred), n)):
        if name not in tables and name not in loose_tables:
            continue
        skeleton = table(name).find("./Table/Skeleton_Set")
        if skeleton is None:
            continue
        groups = skeleton.findall("./Groups/Group")
        for group in sorted(groups, key=lambda g: g.findtext("group", "").lower() != "default"):
            for kind, entries in maps.items():
                for node in group.findall(f"./{kind}s/{kind}"):
                    label = node.findtext("ID", "").lower()
                    for filename in node.findall("./Animation/Filename"):
                        clip = filename.text.lower().removesuffix(".animx").removesuffix(".anim_pc")
                        if label and clip in clips and clip not in entries[label]:
                            entries[label].append(clip)

    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("-- Generated by tools/build_emote_clips.py. SR2 Main Rig clip names.\nreturn {\n")
        for kind, entries in maps.items():
            stream.write(f"  {kind} = {{\n")
            for label, files in sorted(entries.items()):
                values = ", ".join(json.dumps(clip) for clip in files)
                stream.write(f"    [{json.dumps(label)}] = {{ {values} }},\n")
            stream.write("  },\n")
        stream.write("}\n")
    print(f"{len(sets)} compatible tables, {len(maps['State'])} states, {len(maps['Action'])} actions")


if __name__ == "__main__":
    build(Path(sys.argv[1]), Path(sys.argv[2]))
