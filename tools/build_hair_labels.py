"""Map barber label hashes to English names from SR2's customization tables."""
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

from le_strings import key_hash, load


def build(output, strings, tables):
    localized = load(strings)
    labels = {}
    slots = {"head hair", "beard", "mustache", "sideburns", "eyebrows"}
    for path in tables:
        for item in ET.parse(path).findall("./Table/Customization_Item"):
            if item.findtext("Slot", "").lower() not in slots:
                continue
            key = item.findtext("DisplayName")
            if key:
                crc = key_hash(key)
                labels[crc] = localized.get(crc) or item.findtext("Name")
    rows = ["-- Generated by tools/build_hair_labels.py.", "return {"]
    rows.extend(f"  [0x{crc:08X}] = {json.dumps(name, ensure_ascii=False)}," for crc, name in sorted(labels.items()))
    rows.append("}")
    Path(output).write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"{len(labels)} hair label hashes")


if __name__ == "__main__":
    build(sys.argv[1], sys.argv[2], sys.argv[3:])
